package de.voicekeyboard.asr.qwen

import org.json.JSONObject
import java.io.ByteArrayOutputStream
import java.io.File

/**
 * T22e (PLAN_V0146 §6): DETOKENIZER of the Qwen3-ASR model set — decode ONLY.
 * BPE encoding (splitting text into ids) is never needed on the device:
 * the ONNX decoder emits ids, [detokenize] renders text.
 *
 * Reads the Hugging Face `tokenizer.json` (Rust 'tokenizers' serialization —
 * the SAME file that ships in the model package, T22b'):
 *  - `model.vocab`: id → byte-level token piece (GPT-2 bytes_to_unicode
 *    domain, e.g. 'Ġ' = 0x20, 'Ċ' = 0x0A),
 *  - `added_tokens`: ids that are NOT byte-level pieces — `special: true`
 *    ones (chat markers like `<|im_start|>`/`<|im_end|>`) are FILTERED and
 *    never reach the transcription text (silence/hallucination guard, plan §1),
 *  - `decoder.type = "ByteLevel"`: pieces are concatenated and re-assembled
 *    via the inverse bytes_to_unicode table + UTF-8. 'Ġ'→space and 'Ċ'→
 *    newline emerge from the BYTE VALUES, not from string replacement.
 *
 * Goldens: app/src/test/resources/qwen/tokenizer_goldens.json (generated by
 * tools/qwen_ref/gen_tokenizer_goldens.py against the Python reference,
 * `decode(ids, skip_special_tokens=True)`).
 */
class QwenTokenizer private constructor(
    /** id → byte-level piece (base vocabulary). */
    private val vocab: Map<Long, String>,
    /** added_tokens: id → (content, special). Special ones are filtered. */
    private val addedTokens: Map<Long, Pair<String, Boolean>>,
    /** inverse GPT-2 bytes_to_unicode: token char → raw byte. */
    private val byteDecoder: Map<Char, Int>,
) {

    /**
     * ids → text. Special tokens are dropped, unknown ids are skipped
     * (defensively — the engine contract never emits them), everything else
     * is byte-level-concatenated and UTF-8-decoded in one piece.
     */
    fun detokenize(ids: List<Long>): String {
        val bytes = ByteArrayOutputStream()
        val text = StringBuilder()
        for (id in ids) {
            val added = addedTokens[id]
            if (added != null) {
                if (!added.second) {
                    // non-special added token: literal content (none exist in
                    // the Qwen set today, but the format allows it)
                    if (bytes.size() > 0) {
                        text.append(bytes.toString(Charsets.UTF_8)); bytes.reset()
                    }
                    text.append(added.first)
                } // special: filtered
                continue
            }
            val piece = vocab[id] ?: continue
            for (c in piece) byteDecoder[c]?.let { bytes.write(it) }
        }
        if (bytes.size() > 0) text.append(bytes.toString(Charsets.UTF_8))
        return text.toString()
    }

    companion object {

        /** Loads `tokenizer.json` from the model directory (model package, T22b'). */
        fun load(dir: File): QwenTokenizer {
            val root = JSONObject(File(dir, "tokenizer.json").readText())

            val decoderType = root.optJSONObject("decoder")?.optString("type")
            require(decoderType == "ByteLevel") {
                "unsupported tokenizer decoder: $decoderType (T22e supports ByteLevel only)"
            }

            val vocabObj = root.getJSONObject("model").getJSONObject("vocab")
            val vocab = HashMap<Long, String>(vocabObj.length() * 2)
            for (key in vocabObj.keys()) vocab[vocabObj.getLong(key)] = key

            val added = HashMap<Long, Pair<String, Boolean>>()
            root.optJSONArray("added_tokens")?.let { arr ->
                for (i in 0 until arr.length()) {
                    val t = arr.getJSONObject(i)
                    added[t.getLong("id")] = t.getString("content") to t.optBoolean("special", false)
                }
            }
            return QwenTokenizer(vocab, added, gpt2ByteDecoder())
        }

        /**
         * Inverse of the GPT-2 `bytes_to_unicode` table: printable bytes keep
         * their char, all others are mapped into U+0100.. so every byte has a
         * visible token char. Qwen uses the same mapping (decoder ByteLevel).
         */
        private fun gpt2ByteDecoder(): Map<Char, Int> {
            val bytes = mutableListOf<Int>()
            val chars = mutableListOf<Int>()
            fun addRange(from: Char, to: Char) {
                for (c in from..to) {
                    bytes += c.code
                    chars += c.code
                }
            }
            addRange('!', '~')
            addRange('¡', '¬')
            addRange('®', 'ÿ')
            var n = 0
            for (b in 0 until 256) {
                if (b !in bytes) {
                    bytes += b
                    chars += 256 + n
                    n++
                }
            }
            val table = HashMap<Char, Int>(bytes.size * 2)
            for (i in bytes.indices) table[chars[i].toChar()] = bytes[i]
            return table
        }
    }
}
